/**
 * この画面では引っ張って更新（Android）を出さない、という目印。
 *
 * 引っ張って更新は既定では残してある。一覧やカレンダーでは「最新にしたい」に素直に応える動きだからで、
 * 止めるのは、その意味が無いうえに操作を壊す画面だけにする。設定は指で動かす操作（色のスライダー）と
 * この端末の設定（通知）が並ぶ画面で、ユーザー管理は入力の途中でシートが開いている画面なので、
 * 上端からの下向きの動きが再読み込みに化けると、やりかけが消える。
 *
 * 効くのは `src/lib/theme.ts` の `html:has([data-no-pull-to-refresh])`。
 * 置いてある間だけ効くので、画面を移れば自分で消える（後片付けが要らない）。
 * 何も描かないので、置く場所は画面の先頭にする。
 */
export function NoPullToRefresh() {
  return <div data-no-pull-to-refresh hidden />;
}
